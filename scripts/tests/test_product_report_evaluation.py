#!/usr/bin/env python3
"""Protect real product captures and the independently labelled report evaluation boundary."""
import hashlib
import json
from pathlib import Path
import sys
import unittest

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'scripts/reporting'))
from evaluate_product_reports import audit_old, audit_current
FIX=ROOT/'scripts/tests/fixtures/report_product_generation'


class ProductReportEvaluationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.inputs=json.loads((FIX/'frozen-inputs.json').read_text())
        cls.archive=json.loads((FIX/'real-product-archive.json').read_text())
        cls.gold=json.loads((FIX/'gold.json').read_text())

    def test_baseline_is_pinned_to_actual_product_source(self):
        b=self.inputs['baseline']
        self.assertEqual('0459c01b162ba17c0230f8ad8cdf26d02c199f03',b['gitRef'])
        self.assertEqual('be5ad17846a2a319774e93747067b1713ac50c1cd5b07b0ee1166af775a0f88f',b['sha256'])
        self.assertEqual('prd-api/src/PrdAgent.Api/Services/ReportAgent/ReportGenerationService.cs',b['sourcePath'])

    def test_captured_model_input_and_output_are_original_records(self):
        sample=self.inputs['cases'][0];log=self.archive['llmLog']
        self.assertEqual('feb68087-6667-4c29-b917-68c6c2b108f7',sample['sourceLogId'])
        self.assertEqual(log['request'],sample['capturedRequest'])
        self.assertEqual(log['response'],sample['capturedResponse'])
        self.assertEqual(sample['capturedRequest']['messages'][-1]['content'],sample['capturedUserPrompt'])
        self.assertIn('图片生成完成: 10 次',sample['capturedUserPrompt'])
        self.assertIn('网页发布/更新: 8 次',sample['capturedUserPrompt'])

    def test_actual_four_chapter_failure_is_preserved_without_rewriting(self):
        report=next(r for r in self.archive['reports'] if r['id']=='c37a3082b351446da37f7d0408eec3e3')
        self.assertEqual('rule-fallback',report['autoGeneratedBy'])
        self.assertEqual(4,len(report['sections']))
        self.assertEqual('本周未发现明显阻塞风险，建议保持每日同步并提前暴露依赖问题。',report['sections'][1]['items'][0]['content'])
        sample=self.inputs['cases'][1]
        failures=audit_old(sample,{'sections':report['sections']},{'expectedItemIds':[]})
        self.assertEqual(3,len(failures['unsupportedConclusions']))
        self.assertEqual(4,len(failures['missingDirectCitations']))
        self.assertTrue(all('span' in failure for failure in failures['unsupportedConclusions']))

    def test_model_success_and_injected_failure_are_separate(self):
        model,failed=self.inputs['cases'][:2]
        self.assertEqual('captured-model-response',model['upstreamMode'])
        self.assertEqual('upstream-failed',failed['upstreamMode'])
        self.assertEqual(model['activity'],failed['activity'])
        self.assertIn('不是W41线上模型失败记录',failed['provenance'])
        self.assertIn('当前重查历史窗口的计数已变化',self.archive['warning'])

    def test_independent_gold_and_real_source_projection_cover_required_edges(self):
        labels={c['id']:c for c in self.gold['cases']}
        self.assertEqual(set(labels),{c['id'] for c in self.inputs['cases']})
        self.assertIn('real-history-cross-day',labels)
        self.assertIn('real-history-cross-month',labels)
        self.assertIn('real-external-blocker-no-new-activity',labels)
        external=next(c for c in self.inputs['cases'] if c['id']=='real-external-blocker-no-new-activity')
        self.assertEqual([],external['activity']['commits'])
        blocker=next(e for e in external['ledger']['events'] if e['kind']=='blocked')
        self.assertIn('01388f59f73ae6d19d6db5d238731ca8445da8c6',blocker['source']['uri'])
        self.assertIn('凭据',blocker['reason'])
        for sample in self.inputs['cases']:
            for e in sample['ledger']['events']:
                self.assertTrue(e['source']['uri'].startswith('https://'))
                self.assertTrue(e['source']['excerpt'])

    def test_actual_old_compiled_output_matches_original_model_prompt_and_sections(self):
        replay=json.loads((FIX/'retained-old-output.json').read_text())
        self.assertEqual(self.inputs['baseline'],replay['baseline'])
        self.assertEqual(hashlib.sha256((FIX/'frozen-inputs.json').read_bytes()).hexdigest(),replay['sampleInputDigest'])
        first=replay['outputs'][0]
        self.assertFalse(first['old']['usedFallback'])
        self.assertTrue(first['old']['originalPromptMatch'])
        original=next(r for r in self.archive['reports'] if r['id']=='e3f7e777624146b58bedb9b98d698f11')
        original_contents=[[i['content'] for i in section['items']] for section in original['sections']]
        replay_contents=[[i['content'] for i in section['items']] for section in first['old']['sections']]
        self.assertEqual(original_contents,replay_contents)
        self.assertTrue(replay['outputs'][1]['old']['usedFallback'])

    def test_real_captured_model_is_not_falsely_labelled_no_risk_claim(self):
        raw=json.loads(self.archive['llmLog']['response'])
        model=json.loads(raw['choices'][0]['message']['content'])
        failures=audit_old(self.inputs['cases'][0],model,{'expectedItemIds':[]})
        self.assertEqual([],failures['unsupportedConclusions'])
        self.assertEqual(2,len(failures['missingDirectCitations']))


if __name__=='__main__':unittest.main()
