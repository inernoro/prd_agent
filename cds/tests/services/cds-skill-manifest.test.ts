import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { afterEach, describe, expect, it } from 'vitest';
import { buildCdsSkillManifest, copyCdsSkillSource } from '../../src/services/cds-skill-manifest.js';

const skills = ['cds', 'cds-project-scan', 'cds-deploy-pipeline', 'cds-release', 'preview-url'];
const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map(root => fs.rm(root, { recursive: true, force: true }))); });
async function fixture() {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'cds-skill-receipt-')); roots.push(root);
  for (const name of skills) {
    await fs.mkdir(path.join(root, name), { recursive: true });
    await fs.writeFile(path.join(root, name, 'SKILL.md'), `skill ${name}`);
  }
  await fs.mkdir(path.join(root, 'cds/cli'), { recursive: true });
  await fs.writeFile(path.join(root, 'cds/cli/cdscli.py'), 'VERSION = "0.20.0"\n');
  return root;
}
describe('CDS full skill export receipt', () => {
  it('covers all five skills and changes the digest when shipped code changes', async () => {
    const root = await fixture();
    const first = await buildCdsSkillManifest(root);
    expect(first.version).toBe('0.20.0');
    expect(first.skills).toEqual(skills);
    for (const name of skills) expect(first.files[`${name}/SKILL.md`]).toBe(createHash('sha256').update(`skill ${name}`).digest('hex'));
    await fs.writeFile(path.join(root, 'cds/cli/cdscli.py'), 'VERSION = "0.20.1"\n');
    const second = await buildCdsSkillManifest(root);
    expect(second.version).toBe('0.20.1');
    expect(second.files['cds/cli/cdscli.py']).not.toBe(first.files['cds/cli/cdscli.py']);
  });
  it('excludes generated bytecode and the receipt itself', async () => {
    const root = await fixture();
    await fs.mkdir(path.join(root, 'cds/cli/__pycache__'));
    await fs.writeFile(path.join(root, 'cds/cli/__pycache__/old.pyc'), 'stale');
    await fs.writeFile(path.join(root, 'cds/cli/cds-skill-manifest.json'), 'old receipt');
    const manifest = await buildCdsSkillManifest(root);
    expect(Object.keys(manifest.files).some(name => name.includes('__pycache__') || name.endsWith('manifest.json'))).toBe(false);
  });
  it('copies installable source without stale generated bytecode', async () => {
    const root = await fixture();
    await fs.mkdir(path.join(root, 'cds/cli/__pycache__'));
    await fs.writeFile(path.join(root, 'cds/cli/__pycache__/old.pyc'), 'old code');
    const target = path.join(root, 'copied');
    await copyCdsSkillSource(path.join(root, 'cds'), target);
    expect(await fs.readFile(path.join(target, 'cli/cdscli.py'), 'utf8')).toContain('0.20.0');
    await expect(fs.stat(path.join(target, 'cli/__pycache__'))).rejects.toThrow();
  });
  it('rejects links that could pull private files into the bundle', async () => {
    const root = await fixture();
    await fs.symlink('/etc/passwd', path.join(root, 'cds/cli/private-link'));
    await expect(buildCdsSkillManifest(root)).rejects.toThrow('unsupported file type');
    await expect(copyCdsSkillSource(path.join(root, 'cds'), path.join(root, 'copy'))).rejects.toThrow('unsupported file type');
  });
});
