 await page.getByText(`规模验证 ${n}`,{exact:true}).waitFor();
 const requests=[];let recording=true;
 page.on('request',r=>{if(recording&&r.url().includes('/api/'))requests.push({url:new URL(r.url()).pathname+new URL(r.url()).search,method:r.method()});});
 let start=performance.now();
