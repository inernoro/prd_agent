import type { WeeklyReport } from '@/services/contracts/reportAgent';

type GenerationInfo = Pick<WeeklyReport, 'autoGeneratedBy' | 'autoGeneratedModelId' | 'autoGenerationFallbackReason'>;

const GENERATED_BY_LABELS: Record<string, string> = {
  evidence: '证据归纳',
  'rule-fallback': '规则兜底',
};
const FALLBACK_REASON_LABELS: Record<string, string> = {
  'upstream-failed': '模型服务调用失败',
  'empty-response': '模型没有返回内容',
  'invalid-response': '模型返回格式无法识别',
  'empty-items': '模型没有生成有效条目',
};

export function reportGenerationLabel(report: GenerationInfo): string {
  return GENERATED_BY_LABELS[report.autoGeneratedBy || ''] || report.autoGeneratedModelId || '未记录模型';
}

export function reportFallbackReasonLabel(reason?: string): string {
  return FALLBACK_REASON_LABELS[reason || ''] || '模型结果不可用';
}

export function reportGenerationFeedback(report: GenerationInfo): { warning: boolean; message: string } {
  if (report.autoGeneratedBy === 'evidence') {
    return report.autoGenerationFallbackReason
      ? { warning: true, message: '证据归纳草稿已生成；排序模型暂不可用，事实和来源已保留。' }
      : { warning: false, message: '证据归纳草稿已生成，请核查来源并审阅。' };
  }
  return report.autoGeneratedBy === 'rule-fallback'
    ? { warning: true, message: `AI 结果不可用，已生成规则草稿：${reportFallbackReasonLabel(report.autoGenerationFallbackReason)}` }
    : { warning: false, message: `AI 周报草稿已生成（${reportGenerationLabel(report)}）` };
}
