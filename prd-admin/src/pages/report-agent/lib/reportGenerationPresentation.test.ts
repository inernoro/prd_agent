import { describe, expect, it } from 'vitest';
import { reportGenerationFeedback, reportGenerationLabel } from './reportGenerationPresentation';

describe('周报生成来源提示', () => {
  it('证据归纳不显示未记录模型，也不宣称模型撰写正文', () => {
    const report = { autoGeneratedBy: 'evidence' };
    expect(reportGenerationLabel(report)).toBe('证据归纳');
    expect(reportGenerationFeedback(report)).toEqual({ warning: false, message: '证据归纳草稿已生成，请核查来源并审阅。' });
  });
  it('排序模型不可用时明确事实仍保留，避免把证据草稿当生成失败', () => {
    const feedback = reportGenerationFeedback({ autoGeneratedBy: 'evidence', autoGenerationFallbackReason: 'upstream-failed' });
    expect(feedback.warning).toBe(true);
    expect(feedback.message).toContain('排序模型暂不可用');
    expect(feedback.message).toContain('事实和来源已保留');
  });
  it('保持旧规则草稿与旧模型草稿的来源提示', () => {
    expect(reportGenerationLabel({ autoGeneratedBy: 'rule-fallback' })).toBe('规则兜底');
    expect(reportGenerationFeedback({ autoGeneratedBy: 'rule-fallback', autoGenerationFallbackReason: 'empty-response' }).message).toContain('规则草稿');
    expect(reportGenerationLabel({ autoGeneratedBy: 'llm', autoGeneratedModelId: 'actual-model' })).toBe('actual-model');
  });
});
